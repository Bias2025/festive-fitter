#!/usr/bin/env node
/**
 * Generates photoreal "on a person" rack previews for the catalog using
 * Replicate's FLUX Kontext (the same model the live try-on uses), cycling a
 * roster of diverse base-model photos so the rack represents a range of people.
 *
 *   npm run previews                 # every catalog item without a preview yet
 *   npm run previews -- --all        # regenerate all
 *   npm run previews -- --season christmas
 *   npm run previews -- santa elf pj-red-plaid   # just these ids
 *
 * Setup:
 *   1. cp scripts/models.example.json scripts/models.json  and fill in real
 *      photos (paths or URLs). Spread skin tones / ages / body types / genders.
 *   2. Put REPLICATE_API_TOKEN in .env.local (same token as the app).
 *
 * Output: public/outfits/previews/<id>.png  +  refreshes lib/previews.generated.ts
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync } from 'node:fs';
import { dirname, join, extname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const PREVIEW_DIR = join(ROOT, 'public', 'outfits', 'previews');
const MODEL_URL = 'https://api.replicate.com/v1/models/black-forest-labs/flux-kontext-pro/predictions';

function loadEnvToken() {
  if (process.env.REPLICATE_API_TOKEN) return process.env.REPLICATE_API_TOKEN;
  const envPath = join(ROOT, '.env.local');
  if (existsSync(envPath)) {
    for (const line of readFileSync(envPath, 'utf8').split('\n')) {
      const m = line.match(/^\s*REPLICATE_API_TOKEN\s*=\s*(.+?)\s*$/);
      if (m) return m[1].replace(/^["']|["']$/g, '');
    }
  }
  return null;
}

const MIME = { '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.png': 'image/png', '.webp': 'image/webp' };

async function toImageInput(photo) {
  if (/^https?:\/\//.test(photo)) return photo;
  const abs = join(ROOT, photo);
  if (!existsSync(abs)) throw new Error(`model photo not found: ${photo}`);
  const b64 = readFileSync(abs).toString('base64');
  return `data:${MIME[extname(abs).toLowerCase()] || 'image/jpeg'};base64,${b64}`;
}

async function generate(token, imageInput, outfitPrompt) {
  const prompt = `Change the person's outfit to ${outfitPrompt}. Keep the person's face, pose, body proportions, and the background exactly the same. Only change the clothing. Make the new outfit look photorealistic and well-fitted, with natural lighting and shadows that match the original photo.`;

  const res = await fetch(MODEL_URL, {
    method: 'POST',
    headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json', Prefer: 'wait' },
    body: JSON.stringify({
      input: { prompt, input_image: imageInput, output_format: 'png', safety_tolerance: 2 }
    })
  });
  if (!res.ok) throw new Error(`Replicate ${res.status}: ${await res.text()}`);

  let pred = await res.json();
  let tries = 0;
  while (!['succeeded', 'failed', 'canceled'].includes(pred.status) && tries < 40) {
    await new Promise((r) => setTimeout(r, 2000));
    pred = await (await fetch(pred.urls.get, { headers: { Authorization: `Bearer ${token}` } })).json();
    tries++;
  }
  if (pred.status !== 'succeeded') throw new Error(`generation ${pred.status}`);

  const url = Array.isArray(pred.output) ? pred.output[0] : pred.output;
  const img = await fetch(url);
  if (!img.ok) throw new Error(`download failed: ${img.status}`);
  return Buffer.from(await img.arrayBuffer());
}

function refreshRegistry() {
  const ids = existsSync(PREVIEW_DIR)
    ? readdirSync(PREVIEW_DIR)
        .filter((f) => f.endsWith('.png'))
        .map((f) => f.replace(/\.png$/, ''))
        .sort()
    : [];
  const body = ids.length
    ? ids.map((id) => `  ${JSON.stringify(id)}`).join(',\n') + '\n'
    : '  // (no previews generated yet — run `npm run previews`)\n';
  writeFileSync(
    join(ROOT, 'lib', 'previews.generated.ts'),
    `// AUTO-GENERATED by scripts/generate-previews.mjs — do not edit by hand.\n` +
      `// Lists the outfit ids that have a photoreal on-model preview at\n` +
      `// /public/outfits/previews/<id>.png. Regenerate after running the script.\n\n` +
      `export const PREVIEWS: ReadonlySet<string> = new Set<string>([\n${body}]);\n`
  );
  return ids.length;
}

async function main() {
  const argv = process.argv.slice(2);
  const all = argv.includes('--all');
  const seasonIdx = argv.indexOf('--season');
  const season = seasonIdx >= 0 ? argv[seasonIdx + 1] : null;
  const explicitIds = argv.filter((a) => !a.startsWith('--') && a !== season);

  const modelsPath = join(ROOT, 'scripts', 'models.json');
  if (!existsSync(modelsPath)) {
    console.error('Missing scripts/models.json — copy scripts/models.example.json and add real photos.');
    process.exit(1);
  }
  const token = loadEnvToken();
  if (!token) {
    console.error('Missing REPLICATE_API_TOKEN (env or .env.local).');
    process.exit(1);
  }

  const cfg = JSON.parse(readFileSync(modelsPath, 'utf8'));
  const models = (cfg.models || []).filter((m) => m && m.photo && !m.id?.startsWith('_'));
  const overrides = cfg.overrides || {};
  if (!models.length) {
    console.error('scripts/models.json has no usable models.');
    process.exit(1);
  }

  const catalog = JSON.parse(readFileSync(join(ROOT, 'lib', 'catalog.json'), 'utf8'));
  mkdirSync(PREVIEW_DIR, { recursive: true });

  let targets = catalog;
  if (explicitIds.length) targets = catalog.filter((o) => explicitIds.includes(o.id));
  else if (season) targets = catalog.filter((o) => o.season === season);
  if (!all && !explicitIds.length) targets = targets.filter((o) => !existsSync(join(PREVIEW_DIR, `${o.id}.png`)));

  if (!targets.length) {
    console.log('Nothing to generate. (Use --all to regenerate.)');
    return;
  }
  console.log(`Generating ${targets.length} preview(s) with ${models.length} model(s)...\n`);

  const imageCache = new Map();
  let ok = 0;
  for (let i = 0; i < targets.length; i++) {
    const outfit = targets[i];
    const model =
      models.find((m) => m.id === overrides[outfit.id]) || models[i % models.length];
    try {
      if (!imageCache.has(model.id)) imageCache.set(model.id, await toImageInput(model.photo));
      const png = await generate(token, imageCache.get(model.id), outfit.prompt);
      writeFileSync(join(PREVIEW_DIR, `${outfit.id}.png`), png);
      ok++;
      console.log(`  ✓ ${outfit.id}  (${model.label || model.id})`);
    } catch (err) {
      console.log(`  ✗ ${outfit.id}  — ${err.message}`);
    }
  }

  const total = refreshRegistry();
  console.log(`\nDone: ${ok}/${targets.length} generated. ${total} preview(s) registered.`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
